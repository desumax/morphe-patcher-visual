#!/usr/bin/env python3
"""Builds PreviewMapData.java from native/preview_map.json, so the patch needs no resources.

Usage: gen_preview_map_data.py <preview_map.json> <PreviewMapData.java>
"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
text = json.dumps(json.load(open(src, encoding="utf-8")), ensure_ascii=True, separators=(",", ":"))
chunks = [text[i:i + 12000] for i in range(0, len(text), 12000)]
lit = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
body = ",\n            ".join(lit(c) for c in chunks)
open(out, "w", encoding="utf-8").write(f"""/*
 * Generated by visual-editor/bundle/gen_preview_map_data.py from visual-editor/native/preview_map.json.
 * Do not edit by hand.
 */

package app.morphe.extension.youtube.visualeditor;

final class PreviewMapData {{
    private static final String[] PARTS = {{
            {body}
    }};

    static String json() {{
        StringBuilder b = new StringBuilder();
        for (String p : PARTS) b.append(p);
        return b.toString();
    }}

    private PreviewMapData() {{
    }}
}}
""")
